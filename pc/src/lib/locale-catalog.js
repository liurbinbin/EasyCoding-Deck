function normalize(value) {
  return String(value || "").replace(/\s+/g, " ").trim();
}

function translateNormalized(value) {
  const exact = Object.hasOwn(ENGLISH_DETAILS, value) ? ENGLISH_DETAILS[value] : ENGLISH_COPY.get(value);
  if (exact !== undefined) return exact;
  const dynamic = translateDynamicCopy(value, translateNormalized);
  if (dynamic) return dynamic;
  // 操作说明由多个完整句子拼接；逐句翻译，不能只替换开头后留下中文尾部。
  let sentences = value.match(/[^。]+。?|。/g) || [];
  if (sentences.length <= 1 && value.includes("；")) sentences = value.split("；");
  if (sentences.length > 1) {
    const translated = sentences.map(sentence => {
      const part = sentence.trim().replace(/^；/u, "");
      return translateNormalized(part);
    });
    if (translated.every(part => !/[一-鿿]/u.test(part))) return translated.filter(Boolean).join(" ");
  }
  for (const [prefix, replacement] of PREFIX_COPY) {
    if (value.startsWith(prefix)) return replacement + value.slice(prefix.length);
  }
  return value;
}

export function translateText(value) {
  const raw = String(value ?? "");
  const normalized = normalize(raw);
  if (!normalized) return raw;
  const translated = translateNormalized(normalized);
  if (translated === normalized) return raw;
  // JSX 会产生多行和缩进，不能用折叠空白后的字符串去匹配原始文本。
  const leading = raw.match(/^\s*/u)[0];
  const trailing = raw.match(/\s*$/u)[0];
  return leading + translated + trailing;
}

